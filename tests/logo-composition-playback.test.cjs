'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('icon-logo-motion-studio.js', 'utf8');
assert.match(source, /name:'Komposisi Logo'/, 'studio starts as one logo composition, not Intro/Discover/Outro');
assert.doesNotMatch(source, /name:'Intro'|name:'Discover'|name:'Outro'/, 'storyboard defaults are removed');
assert.match(source, /let tickScene=-1;function tick\(now\)/, 'playback tracks scene changes');
assert.match(source, /else\{const t=localTime\(\);currentScene\(\)\.layers\.forEach/, 'playback updates visibility without rebuilding SVG every frame');
assert.match(source, /Acak Komposisi/, 'random non-repeating composition tool is available');
assert.match(source, /tm4AddEight/, 'batch add eight logos tool is available');
assert.match(source, /tm4MirrorSet/, 'horizontal mirror tool is available');
assert.match(source, /tm4RandomStyle/, 'motion and color randomizer is available');
assert.match(source, /tm4ArrangeGrid/, 'automatic grid layout is available');
assert.ok(source.includes('function play(){state.playing=!state.playing;state.last=0;if(state.playing){tickScene=state.scene;'), 'first playback frame preserves the existing SVG DOM');
assert.match(source, /id="tm4PartMotion"/, 'semantic part animation selector is exposed');
assert.match(source, /id="tm4Expression"/, 'character expression selector is exposed');
assert.match(source, /id="tm4PartsEnabled"/, 'per-part animation can be enabled or disabled');
assert.match(source, /id="tm4SaveProject"/, 'project save control is available');
assert.match(source, /id="tm4LoadProject"/, 'project load control is available');
const duplicateIds = [...source.matchAll(/id="([^"]+)"/g)].map(match => match[1]).filter((id, i, ids) => ids.indexOf(id) !== i);
assert.deepEqual([...new Set(duplicateIds)], [], 'Logo Studio markup must not contain duplicate IDs');
console.log('Logo composition and playback regression checks passed.');

assert.match(source, /visible:true,locked:false/, 'new layers default to visible and unlocked');
assert.match(source, /data-layer-visible=/, 'each layer exposes a visibility toggle');
assert.match(source, /data-layer-lock=/, 'each layer exposes a lock toggle');
assert.match(source, /filter\(l=>l\.visible!==false\)/, 'hidden layers are excluded from composition output');
assert.match(source, /pointer-events:'\+\(l\.locked\?'none':'auto'\)/, 'locked layers are protected from preview interaction');
